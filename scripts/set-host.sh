#!/usr/bin/env bash
# Waits for the NGINX load balancer, writes its DNS name into
# charts/cloudnative-app/values-host.yaml and pushes it, so Argo CD sets the Ingress host.
# Usage: bash scripts/set-host.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

CTX="$(kubectl config current-context)"
case "$CTX" in
  *cnm-dev-eks*) ;;
  *) echo "STOP: kubectl context is '$CTX', not the EKS cluster."; exit 1 ;;
esac

echo ">> Waiting for the load balancer hostname (up to 10 minutes)"
LB=""
for i in $(seq 1 60); do
  LB="$(kubectl get svc -n nginx-ingress nginx-ingress-controller \
        -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2>/dev/null || true)"
  [ -n "$LB" ] && break
  echo "   not ready yet ($i/60)..."; sleep 10
done
[ -n "$LB" ] || { echo "Load balancer hostname not available. Check: kubectl get svc -n nginx-ingress"; exit 1; }

cat > charts/cloudnative-app/values-host.yaml <<YAML
# GENERATED by scripts/set-host.sh - the NLB hostname used as the Ingress host
ingress:
  host: $LB
YAML

git add charts/cloudnative-app/values-host.yaml
if ! git diff --cached --quiet; then
  git commit -m "Set ingress host to the NLB hostname"
  git pull --rebase --autostash
  git push
fi

echo
echo ">> Argo CD will apply this within about a minute."
echo "   App URL:  http://$LB"
